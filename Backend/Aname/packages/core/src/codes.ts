export type AmaneCodeName = keyof typeof AMANE_CODES;

const BY_NUMBER = new Map<number, AmaneCodeName>(Object.entries(AMANE_CODES).map(([k, v]) => [v, k as AmaneCodeName]));

export function amaneCodeName(code: number | bigint | string): AmaneCodeName | undefined {
  return BY_NUMBER.get(Number(code));
}
